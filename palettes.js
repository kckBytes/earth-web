const SC = [temp, rate, rate, wind, gust, pres, cape, rh, snow, wave];
export function buildPalettes() {
  const b = new Uint8Array(PW * PROWS * 4);
  for (let r = 0; r < ROWS.length; r++) {
    const st = ROWS[r], sc = SC[r];
    for (let x = 0; x < PW; x++) {
      const u = x / (PW - 1);
      let k = 0;
      while (k < st.length - 2 && sc(st[k + 1][0]) < u) k++;
      const p0 = sc(st[k][0]), p1 = sc(st[k + 1][0]), f = Math.max(0, Math.min(1, (u - p0) / Math.max(1e-9, p1 - p0)));
      for (let i = 0; i < 4; i++) b[(r * PW + x) * 4 + i] = Math.round((st[k][i + 1] + f * (st[k + 1][i + 1] - st[k][i + 1])) * 255);
    }
  }
  return b;
}
